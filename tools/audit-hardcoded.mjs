// Lists every hard-coded Wilmington / NC / beach-town / domain / tax / timezone / lat-long string, by file and count.
// Run: node tools/audit-hardcoded.mjs [--root .] [--out city-pack/HARDCODED-REPORT.md] [--json] [--top 25]
// Read-only apart from writing the report. Sizes a clone effort; it does not change any page.
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : d; };
const root = path.resolve(opt('root', '.'));
const out = opt('out', 'city-pack/HARDCODED-REPORT.md');
const top = +opt('top', 25);
const asJson = args.includes('--json');

const SKIP_DIRS = new Set(['.git', 'node_modules', 'vendor', 'city-pack', 'img', 'icons', 'shop-art']);
const SKIP_FILES = new Set(['package-lock.json', 'audit-hardcoded.mjs', 'thin-content-gate.mjs']);
const TEXT_EXT = new Set(['.html', '.js', '.mjs', '.css', '.json', '.txt', '.xml', '.toml', '.webmanifest', '.md', '.csv']);

// category -> [label, regex]. Each match counts once.
const RULES = [
  ['city', 'Wilmington', /\bWilmington\b/gi],
  ['city', 'New Hanover', /\bNew Hanover\b/gi],
  ['city', 'Cape Fear', /\bCape Fear\b/gi],
  ['towns', 'Wrightsville', /\bWrightsville\b/gi],
  ['towns', 'Carolina Beach', /\bCarolina Beach\b/gi],
  ['towns', 'Kure Beach', /\bKure Beach\b/gi],
  ['towns', 'Fort Fisher / Masonboro / Figure Eight / Pleasure Island', /\b(Fort Fisher|Masonboro|Figure Eight|Pleasure Island|Topsail|Southport|Oak Island)\b/gi],
  ['state', 'North Carolina / NC', /\b(North Carolina|N\.C\.)\b|\bNC\b/g],
  ['domain', 'shorelist.net', /shorelist\.net/gi],
  ['domain', 'shorelist.shop', /shorelist\.shop/gi],
  ['domain', 'gmail/ops email', /shorelistwilmington@gmail\.com|rj@shorelist\.net/gi],
  ['brand', 'ShoreList (brand name)', /\bShoreList\b/g],
  ['tax', 'tax rate / NC tax', /\bTAX_RATE\b|\b0\.07\b|\b4\.75%|\b2\.25%|\bsales tax\b/gi],
  ['timezone', 'America/New_York, EDT/EST', /America\/New_York|\bEDT\b|\bEST\b|-04:00|-05:00/g],
  ['latlng', 'lat/long literals (33-35 N, -77/-78 W)', /(?<![\d.])-?7[78]\.\d{2,}|(?<![\d.])3[34]\.\d{2,}/g],
  ['latlng', 'lat/lon keys', /\b(lat|lon|lng|latitude|longitude)\b\s*[:=]/gi],
  ['analytics', 'GA4 id', /\bG-[A-Z0-9]{8,}\b/g],
  ['stripe', 'Stripe ids / account refs', /\b(acct|price|prod|pk_live|pk_test)_[A-Za-z0-9]{6,}/g],
  ['noaa', 'NOAA station / tide', /\b8658163\b|tidesandcurrents/gi],
  ['operators', 'Operator ids/names baked in code', /\b(wwt-[a-z]+|cbt-[a-z]+|ron-film|sean-ghost|james-surf|nature-walk)\b/g],
];

const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(path.join(d, e.name)); continue; }
    if (SKIP_FILES.has(e.name) || !TEXT_EXT.has(path.extname(e.name))) continue;
    const p = path.join(d, e.name);
    if (fs.statSync(p).size > 8e6) continue;
    files.push(p);
  }
})(root);

// Generated vs hand-edited: events/*.html and search/llms outputs are produced by tools, so fixing the generator fixes them.
const kindOf = (rel) => /^events\/.+\.html$/.test(rel) || /^things-to-do\/.+\.html$/.test(rel) || ['search-index.json', 'llms.txt', 'llms-full.txt', 'sitemap.xml'].includes(rel) ? 'generated'
  : /^(tools|netlify)\//.test(rel) ? 'generator/function'
  : /\.(js|css)$/.test(rel) ? 'client script' : /\.html$/.test(rel) ? 'page' : 'data/config';

const perFile = {}, catTotals = {}, labelTotals = {};
for (const f of files) {
  const rel = path.relative(root, f).split(path.sep).join('/');
  const txt = fs.readFileSync(f, 'utf8');
  const row = { total: 0, byCat: {}, kind: kindOf(rel) };
  for (const [cat, label, re] of RULES) {
    const n = (txt.match(re) || []).length;
    if (!n) continue;
    row.byCat[cat] = (row.byCat[cat] || 0) + n;
    // brand name is expected on every page and is not a city fact, so keep it out of the hardcode total
    if (cat !== 'brand') row.total += n;
    catTotals[cat] = (catTotals[cat] || 0) + n;
    labelTotals[label] = (labelTotals[label] || 0) + n;
  }
  if (Object.keys(row.byCat).length) perFile[rel] = row;
}
const ranked = Object.entries(perFile).filter(([, r]) => r.total > 0).sort((a, b) => b[1].total - a[1].total);
const grand = ranked.reduce((s, [, r]) => s + r.total, 0);
const kindTotals = {};
for (const [, r] of ranked) { const k = (kindTotals[r.kind] ||= { files: 0, hits: 0 }); k.files++; k.hits += r.total; }

if (asJson) { console.log(JSON.stringify({ grand, catTotals, labelTotals, kindTotals, perFile }, null, 1)); process.exit(0); }

const cats = Object.keys(catTotals).filter((c) => c !== 'brand').sort((a, b) => catTotals[b] - catTotals[a]);
const L = [];
L.push('# Hard-coded city strings report', '',
  `Generated by \`node tools/audit-hardcoded.mjs\` (scans ${files.length} text files under the repo root; skips .git, node_modules, vendor, img, icons, shop-art, city-pack). Regenerate after any refactor to measure progress.`, '',
  '"Hits" are regex matches, not unique strings. The brand name "ShoreList" is counted separately and left out of file totals, because it is a brand token and not a city fact. Hits in `generated` files disappear when the generator that writes them reads the pack; hits in `generator/function`, `client script` and `page` files need real refactoring.', '',
  '## Summary', '',
  `- Files with at least one hit: **${ranked.length}**`, `- Total hits (excluding brand name): **${grand}**`, `- Brand name "ShoreList" occurrences: **${catTotals.brand || 0}**`, '',
  '### By kind of file', '', '| Kind | Files | Hits |', '|---|---:|---:|',
  ...Object.entries(kindTotals).sort((a, b) => b[1].hits - a[1].hits).map(([k, v]) => `| ${k} | ${v.files} | ${v.hits} |`), '',
  '### By category', '', '| Category | Hits |', '|---|---:|', ...cats.map((c) => `| ${c} | ${catTotals[c]} |`), '',
  '### By pattern', '', '| Pattern | Hits |', '|---|---:|',
  ...Object.entries(labelTotals).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k.replace(/\|/g, '\\|')} | ${v} |`), '',
  `## Top ${top} hotspots`, '', '| # | File | Kind | Hits | Main categories |', '|---:|---|---|---:|---|',
  ...ranked.slice(0, top).map(([f, r], i) => `| ${i + 1} | \`${f}\` | ${r.kind} | ${r.total} | ${Object.entries(r.byCat).filter(([c]) => c !== 'brand').sort((a, b) => b[1] - a[1]).slice(0, 4).map(([c, n]) => `${c} ${n}`).join(', ')} |`), '',
  '## Every file', '', '| File | Kind | Hits | ' + cats.join(' | ') + ' |', '|---|---|---:|' + cats.map(() => '---:').join('|') + '|',
  ...ranked.map(([f, r]) => `| \`${f}\` | ${r.kind} | ${r.total} | ` + cats.map((c) => r.byCat[c] || '').join(' | ') + ' |'), '');
fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
fs.writeFileSync(out, L.join('\n'));
console.log(`audit: ${ranked.length} files, ${grand} hits -> ${out}`);
for (const [f, r] of ranked.slice(0, 8)) console.log(`  ${String(r.total).padStart(5)}  ${f}`);
